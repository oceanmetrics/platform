// writes src/glyphs.ts: the Ocean Metrics mark and the three sprite glyphs the bar draws, read from the published brand
// kit, never typed by hand (indicators CLAUDE.md "Icons"). the sources are the site checkout beside platform:
//   static/img/logos/ocean-metrics-mark.svg       the ensō mark (two ring strokes, one waterline)
//   static/brand/v1/icons/om-icons.svg            the sprite served at https://oceanmetrics.io/brand/v1/icons/
// usage: node scripts/glyphs.mjs [site-checkout]      (default ../../../oceanmetrics.github.io, or $OM_SITE_DIR)
// test/glyphs.test.ts runs glyphSource() on the same files and fails when src/glyphs.ts is stale.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const HERE = new URL('..', import.meta.url).pathname
export const SITE_DIR = process.env.OM_SITE_DIR ?? join(HERE, '../../../oceanmetrics.github.io')
export const MARK_FILE = 'static/img/logos/ocean-metrics-mark.svg'
export const SPRITE_FILE = 'static/brand/v1/icons/om-icons.svg'
export const GLYPHS = ['ui-search', 'ui-more', 'ui-close']

/**
 * a path's numbers rounded to 0.1 of the mark's 2048 grid (at most 0.05 off: 0.0008 px at the bar's 26 px, 0.025 px
 * even at 1024 px) and the spaces around its commands dropped. the shape is the published one; the bytes are 30% fewer
 * (1,554 B gzip for the three paths as published, 1,100 rounded).
 */
export function tidyPath(d) {
  return d.replace(/-?\d+\.?\d*/g, (n) => String(+(+n).toFixed(1))).replace(/ ?([MCLZz]) ?/g, '$1').replace(/ -/g, '-')
}

/** the d strings of the mark: the ring paths (inside the currentColor group), then the waterline, tidied */
export function markPaths(svg) {
  const all = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) => tidyPath(m[1]))
  if (all.length !== 3) throw new Error(`the mark has ${all.length} paths, expected 3 (two ring strokes, one waterline)`)
  return { ring: all.slice(0, 2), spark: all[2] }
}

/** the d string of one sprite symbol (a single path on the 24-px grid) */
export function symbolPath(sprite, id) {
  const m = new RegExp(`<symbol id="${id}" viewBox="0 0 24 24">\\s*<path[^>]*\\bd="([^"]+)"`).exec(sprite)
  if (!m) throw new Error(`glyph ${id} not in the sprite`)
  return m[1]
}

export function glyphSource(dir = SITE_DIR) {
  const mark = markPaths(readFileSync(join(dir, MARK_FILE), 'utf8'))
  const sprite = readFileSync(join(dir, SPRITE_FILE), 'utf8')
  const lines = [
    '// GENERATED by scripts/glyphs.mjs from the published brand kit (oceanmetrics.github.io ' + MARK_FILE + ' and',
    '// ' + SPRITE_FILE + ', https://oceanmetrics.io/brand/v1/icons/). do not hand-edit: run `npm run glyphs -w packages/nav`.',
    '// MDI glyphs: Material Design Icons (Pictogrammers, Apache-2.0).',
    '',
    '/** the ensō mark on its 2048 grid (numbers to 0.1, tidyPath): the ring strokes take the text colour, the waterline the fixed spark */',
    `export const MARK_RING: readonly string[] = ${JSON.stringify(mark.ring)}`,
    `export const MARK_SPARK = ${JSON.stringify(mark.spark)}`,
    '',
    '/** the sprite glyphs the bar draws, on the 24-px grid */',
    'export const GLYPH = {',
    ...GLYPHS.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(symbolPath(sprite, id))},`),
    '} as const',
    '',
  ]
  return lines.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = join(HERE, 'src/glyphs.ts')
  writeFileSync(out, glyphSource(process.argv[2] ?? SITE_DIR))
  console.log(`wrote ${out}`)
}
