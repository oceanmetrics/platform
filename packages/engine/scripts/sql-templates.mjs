// writes src/sqlTemplates.ts from sql/*.sql: each template as a string constant, so `tsc` builds the package with
// the SQL inside it (no bundler `?raw` import, no file read at run time). run by `npm run build` before tsc; the file
// is committed, and test/sqlTemplates.test.ts fails when it is stale (`node scripts/sql-templates.mjs` fixes it).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const names = readdirSync(join(ROOT, 'sql')).filter((f) => f.endsWith('.sql')).sort()
const body = names.map((f) => `  ${f.replace(/\.sql$/, '')}: ${JSON.stringify(readFileSync(join(ROOT, 'sql', f), 'utf8'))},`).join('\n')
writeFileSync(join(ROOT, 'src', 'sqlTemplates.ts'), `// generated by scripts/sql-templates.mjs from sql/*.sql: do not edit (edit the .sql, then run the script)
export const TEMPLATES: Readonly<Record<string, string>> = {
${body}
}
`)
console.log(`sqlTemplates.ts: ${names.length} templates`)
